def ending_text(ending_id: str, class_id: str = "") -> tuple:
    """Каркас концовки плюс голос класса."""
    title, body = ENDINGS.get(ending_id, ('КОНЕЦ', ''))
    extra = ENDING_POSTSCRIPTS.get((ending_id, class_id), "")
    if extra:
        body = f"{body} {extra}"
    return title, body

